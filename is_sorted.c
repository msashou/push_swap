#include "push_swap.h"

int	is_sorted(int *arr, int size)
{
	int		i;

	if (size <= 1)
		return (1);
	i = 0;
	while (i < size - 1)
	{
		if (arr[i] > arr[i + 1])
			return (0);
		i++;
	}
	return (1);
}
